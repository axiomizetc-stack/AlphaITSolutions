const LANGS = ["en", "bs", "hr", "sr", "de", "ru"];
const HTML_LANG = { en: "en", bs: "bs", hr: "hr", sr: "sr-Cyrl", de: "de", ru: "ru" };

function normalizeLang(lang) {
  return LANGS.includes(lang) ? lang : "en";
}

const nav = document.querySelector("#nav");
const toggle = document.querySelector(".menu-toggle");

function applyLanguage(lang) {
  const chosen = normalizeLang(lang);
  const pack = translations[chosen] || translations.en;
  document.documentElement.lang = HTML_LANG[chosen] || "en";
  document.documentElement.dataset.lang = chosen;
  document.title = pack["meta.title"];
  document.querySelector('meta[name="description"]').setAttribute("content", pack["meta.description"]);
  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogTitle) ogTitle.setAttribute("content", pack["meta.title"]);
  if (ogDesc) ogDesc.setAttribute("content", pack["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = pack[node.dataset.i18n];
    if (typeof value === "string") node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = pack[node.dataset.i18nPlaceholder];
    if (typeof value === "string") node.placeholder = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = pack[node.dataset.i18nAria];
    if (typeof value === "string") node.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === chosen));
  });

  try {
    localStorage.setItem("alpha-lang", chosen);
  } catch {
    /* private browsing */
  }
}

toggle.addEventListener("click", () => {
  const open = nav.classList.toggle("is-open");
  toggle.setAttribute("aria-expanded", String(open));
});

nav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    nav.classList.remove("is-open");
    toggle.setAttribute("aria-expanded", "false");
  });
});

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

let saved = "en";
try {
  saved = normalizeLang(localStorage.getItem("alpha-lang"));
} catch {
  saved = "en";
}
applyLanguage(saved);

const form = document.querySelector("#order-form");
const statusEl = document.querySelector("#form-status");

form.addEventListener("submit", (event) => {
  event.preventDefault();
  const lang = normalizeLang(document.documentElement.dataset.lang);
  const pack = translations[lang] || translations.en;
  const data = Object.fromEntries(new FormData(form));
  statusEl.classList.remove("is-error");

  if (!data.name.trim()) {
    statusEl.textContent = pack["form.needName"];
    statusEl.classList.add("is-error");
    return;
  }
  if (!data.phone.trim()) {
    statusEl.textContent = pack["form.needPhone"];
    statusEl.classList.add("is-error");
    return;
  }

  const typeLabel = form.querySelector(`[name="type"] option[value="${data.type}"]`)?.textContent || data.type;
  const labels = pack["form.labels"];
  const lines = [
    pack["form.hello"],
    `${labels.name}: ${data.name.trim()}`,
    `${labels.phone}: ${data.phone.trim()}`,
    `${labels.type}: ${typeLabel}`,
    data.message.trim() ? `${labels.message}: ${data.message.trim()}` : "",
  ].filter(Boolean);

  statusEl.textContent = pack["form.opening"];
  window.open(`https://wa.me/38761834552?text=${encodeURIComponent(lines.join("\n"))}`, "_blank", "noopener,noreferrer");
});
